// Builds the public catalog (challenges + packs) and writes it into the homepage, catalog.json and
// status.html.
//
// Sources:
//   - examples/*/challenge.yaml  → the built-in pack ("built-in" badge). Only the public allowlist
//     below is read; workspace/, checks/, solution/ and debrief/ are never opened.
//   - registry/index.json        → community packs already verified by registry/crawl.py in CI
//     ("community · verified" badge). It carries the same public fields only.
//   - registry/status.json       → every source the crawler saw, for status.html.
//
// Usage: node scripts/catalog.mjs            write outputs
//        node scripts/catalog.mjs --check    exit 1 if any output is stale

import { readFile, readdir, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const root = new URL("../../", import.meta.url);
const publicRoot = new URL("../public/", import.meta.url);
const htmlPath = new URL("index.html", publicRoot);
const jsonPath = new URL("catalog.json", publicRoot);
const statusHtmlPath = new URL("status.html", publicRoot);
const indexPath = new URL("registry/index.json", root);
const statusPath = new URL("registry/status.json", root);
const repo = "https://github.com/franndeli/patchground";

export const PUBLIC_FIELDS = ["id", "title", "summary", "type", "languages", "tags", "difficulty", "timebox_minutes", "provenance"];
const START = "<!-- catalog:start (generated by scripts/catalog.mjs; do not edit by hand) -->";
const END = "<!-- catalog:end -->";
const PACKS_START = "<!-- packs:start (generated by scripts/catalog.mjs; do not edit by hand) -->";
const PACKS_END = "<!-- packs:end -->";

const unquote = (s) => (/^(["']).*\1$/.test(s) ? s.slice(1, -1) : s);
const escape = (s) => String(s).replace(/[&<>"]/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" }[c]));
const title = (s) => s.charAt(0).toUpperCase() + s.slice(1);
const pad = (n) => String(n).padStart(2, "0");
const day = (iso) => (typeof iso === "string" ? iso.slice(0, 10) : "");
// Community data is untrusted: only plain https links and non-negative integer counts reach the page.
export const httpsUrl = (u) => (typeof u === "string" && /^https:\/\/[^\s"'<>`\\]+$/.test(u) ? u : null);
const count = (n) => (Number.isSafeInteger(n) && n >= 0 ? n : 0);

/** Minimal reader for the flat top-level scalars, inline lists and folded blocks we publish. */
export function readPublicMetadata(yaml) {
  const lines = yaml.split("\n");
  const out = {};
  for (let i = 0; i < lines.length; i++) {
    const match = lines[i].match(/^([a-z_]+):\s*(.*)$/);
    if (!match || !PUBLIC_FIELDS.includes(match[1])) continue;
    const [, key, raw] = match;
    if (raw === ">-" || raw === ">" || raw === "|") {
      const block = [];
      while (lines[i + 1]?.startsWith("  ")) block.push(lines[++i].trim());
      out[key] = block.join(" ");
    } else if (raw.startsWith("[")) {
      out[key] = raw.slice(1, raw.lastIndexOf("]")).split(",").map((s) => unquote(s.trim())).filter(Boolean);
    } else {
      out[key] = unquote(raw);
    }
  }
  if (out.timebox_minutes) out.timebox_minutes = Number(out.timebox_minutes);
  return out;
}

async function loadBuiltIn() {
  const examples = new URL("examples/", root);
  const dirs = (await readdir(examples, { withFileTypes: true })).filter((d) => d.isDirectory()).map((d) => d.name).sort();
  const challenges = [];
  for (const name of dirs) {
    const meta = readPublicMetadata(await readFile(new URL(`${name}/challenge.yaml`, examples), "utf8"));
    if (meta.id !== name) throw new Error(`examples/${name}: manifest id "${meta.id}" does not match its folder`);
    challenges.push({ ...meta, pack: "patchground-examples", ticket: `${repo}/blob/main/examples/${name}/TICKET.md` });
  }
  return {
    name: "patchground-examples", kind: "built-in", description: "Curated examples shipped with the CLI; validated in this repository's CI on every push.",
    source: repo, homepage: `${repo}/tree/main/examples`, challenges, stars: null, forks: null, verified_at: null, first_seen: null,
  };
}

async function readJson(url, fallback) {
  try { return JSON.parse(await readFile(url, "utf8")); } catch { return fallback; }
}

async function loadCommunity() {
  const index = await readJson(indexPath, { packs: [] });
  return (index.packs || []).map((p) => ({
    name: p.name, kind: "community", description: p.description, version: p.version, source: httpsUrl(p.source), homepage: httpsUrl(p.homepage) || httpsUrl(p.source) || "./status.html",
    host: p.host, commit: p.commit, verified_at: p.verified_at, first_seen: p.first_seen, stars: count(p.stars), forks: count(p.forks),
    challenges: (p.challenges || []).map((c) => ({
      ...Object.fromEntries(PUBLIC_FIELDS.filter((k) => k in c).map((k) => [k, c[k]])),
      pack: p.name, ticket: httpsUrl((p.tickets || {})[c.id]) || httpsUrl(p.homepage) || httpsUrl(p.source) || "./status.html",
    })),
  }));
}

export async function loadCatalog() {
  const packs = [await loadBuiltIn(), ...(await loadCommunity())];
  const order = { beginner: 0, intermediate: 1, advanced: 2 };
  const challenges = packs.flatMap((p) => p.challenges)
    .sort((a, b) => (order[a.difficulty] ?? 9) - (order[b.difficulty] ?? 9) || a.timebox_minutes - b.timebox_minutes || a.id.localeCompare(b.id));
  return { packs, challenges };
}

function badge(pack) {
  return pack.kind === "built-in"
    ? `<span class="badge badge-builtin">built-in</span>`
    : `<span class="badge badge-verified" title="Passed pgnd validate in Patchground CI">verified · ${escape(day(pack.verified_at))}</span>`;
}

export function renderCatalog({ packs, challenges }) {
  const byName = Object.fromEntries(packs.map((p) => [p.name, p]));
  const types = [...new Set(challenges.map((e) => e.type))];
  const languages = [...new Set(challenges.flatMap((e) => e.languages))];
  const difficulties = ["beginner", "intermediate", "advanced"].filter((d) => challenges.some((e) => e.difficulty === d));
  const community = packs.filter((p) => p.kind === "community");
  const summaryLine = `${challenges.length} ${challenges.length === 1 ? "challenge" : "challenges"} in ${packs.length} ${packs.length === 1 ? "pack" : "packs"} · ${languages.map(title).join(", ")} · ${types.map(title).join(", ")}`;
  // Facets stay bounded as the catalog grows; a facet with one value adds no button. Tags are kept
  // on each card (data-tags) and searched by the text box rather than rendered as filters.
  const facets = [...difficulties, ...(types.length > 1 ? types : []), ...(languages.length > 1 ? languages : []), ...(community.length ? ["community"] : [])];
  const count = (facet) => challenges.filter((e) => [e.difficulty, e.type, ...e.languages, byName[e.pack].kind].includes(facet)).length;

  const filters = [
    `<button type="button" class="filter" data-filter="all" aria-pressed="true">All <span>${pad(challenges.length)}</span></button>`,
    ...facets.map((f) => `<button type="button" class="filter" data-filter="${escape(f)}" aria-pressed="false">${escape(title(f))} <span>${pad(count(f))}</span></button>`),
  ].join("");

  const cards = challenges.map((e, i) => {
    const pack = byName[e.pack];
    return `
          <article class="challenge-card" data-facets="${escape([e.difficulty, e.type, ...e.languages, pack.kind].join(" "))}" data-tags="${escape(e.tags.join(" "))}" data-search="${escape([e.title, e.summary, e.tags.join(" "), e.pack].join(" ").toLowerCase())}" data-challenge="${escape(e.id)}" data-pack="${escape(e.pack)}">
            <span class="challenge-number" aria-hidden="true">${pad(i + 1)}</span>
            <div class="challenge-summary">
              <h3><a href="${escape(e.ticket)}">${escape(e.title)}<span class="sr-only"> — read the ticket</span></a></h3>
              <p>${escape(e.summary)}</p>
              <p class="challenge-pack"><span class="pack-chip">${escape(e.pack)}</span>${badge(pack)}</p>
            </div>
            <div class="challenge-topic"><span>${escape(e.languages.map(title).join(" / "))} / ${escape(title(e.type))} · ${e.tags.map(escape).join(", ")}</span><span class="difficulty">${escape(title(e.difficulty))}${e.provenance === "generated" ? " · AI-generated" : ""}</span></div>
            <span class="timebox">${e.timebox_minutes} MIN</span>
            <span class="row-arrow" aria-hidden="true">↗</span>
          </article>`;
  }).join("");

  return `${START}
        <div class="catalog-toolbar"><div class="filters" role="group" aria-label="Filter challenges" hidden>${filters}</div><label class="search" hidden><span class="sr-only">Search challenges by title, tag or pack</span><input type="search" id="catalog-search" placeholder="Search title, tag, pack…" autocomplete="off"></label><p class="catalog-count" role="status" aria-live="polite" aria-atomic="true" id="catalog-count" data-summary="${escape(summaryLine)}">${escape(summaryLine)}</p></div>
        <div class="challenge-list">${cards}
          <p class="catalog-empty" id="catalog-empty" hidden>No challenge matches. Clear the search or pick another filter.</p>
        </div>
        ${END}`;
}

export function renderPacks(packs) {
  const community = packs.filter((p) => p.kind === "community");
  const cards = packs.map((p) => {
    const types = [...new Set(p.challenges.map((c) => c.type))].map(title).join(", ");
    const stats = p.kind === "community"
      ? `<span>★ ${p.stars}</span><span>⑂ ${p.forks}</span><span>verified ${escape(day(p.verified_at))}</span>`
      : `<span>validated in CI on every push</span>`;
    return `
          <article class="pack-card" data-kind="${p.kind}" data-stars="${p.stars ?? -1}" data-verified="${escape(p.verified_at || "")}" data-first-seen="${escape(p.first_seen || "")}" data-count="${p.challenges.length}">
            <div class="pack-head"><h3><a href="${escape(p.homepage)}">${escape(p.name)}<span aria-hidden="true"> ↗</span></a></h3>${badge(p)}</div>
            <p>${escape(p.description)}</p>
            <p class="pack-meta"><span>${p.challenges.length} ${p.challenges.length === 1 ? "challenge" : "challenges"}</span><span>${escape(types)}</span>${stats}</p>
          </article>`;
  }).join("");
  const empty = community.length ? "" : `
          <p class="packs-empty">No community pack has been verified yet. Publish yours and it will appear here after the next registry run.</p>`;
  return `${PACKS_START}
        <div class="packs-toolbar"><p class="catalog-count">${packs.length} ${packs.length === 1 ? "pack" : "packs"} · ${community.length} community</p><label class="sort" hidden><span>Sort by</span><select id="pack-sort"><option value="stars">Most starred</option><option value="verified">Recently verified</option><option value="newest">Newest</option><option value="count">Most challenges</option></select></label></div>
        <div class="pack-grid" id="pack-grid">${cards}${empty}
        </div>
        ${PACKS_END}`;
}

