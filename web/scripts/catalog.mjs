function replaceRegion(html, start, end, content) {
  const a = html.indexOf(start);
  const b = html.indexOf(end);
  if (a < 0 || b < 0) throw new Error(`index.html is missing the ${start.slice(5, 20)} markers`);
  return html.slice(0, a) + content + html.slice(b + end.length);
}

export async function build({ check = false } = {}) {
  const catalog = await loadCatalog();
  const status = await readJson(statusPath, { seen: [] });
  const json = `${JSON.stringify({
    schema: "patchground-web-catalog/1",
    generated_from: ["examples/*/challenge.yaml (public fields only)", "registry/index.json"],
    fields: PUBLIC_FIELDS,
    packs: catalog.packs.map(({ challenges, ...p }) => ({ ...p, challenge_count: challenges.length })),
    challenges: catalog.challenges,
  }, null, 2)}\n`;
  const html = await readFile(htmlPath, "utf8");
  let next = replaceRegion(html, START, END, renderCatalog(catalog));
  next = replaceRegion(next, PACKS_START, PACKS_END, renderPacks(catalog.packs));
  const statusHtml = renderStatus(status, catalog.packs);
  const stale = next !== html
    || (await readFile(jsonPath, "utf8").catch(() => "")) !== json
    || (await readFile(statusHtmlPath, "utf8").catch(() => "")) !== statusHtml;
  if (check) {
    if (stale) throw new Error("Catalog is stale: run `npm --prefix web run catalog`");
    return { ...catalog, stale };
  }
  await writeFile(htmlPath, next);
  await writeFile(jsonPath, json);
  await writeFile(statusHtmlPath, statusHtml);
  return { ...catalog, stale };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes("--check");
  build({ check })
    .then(({ challenges, packs, stale }) => console.log(check
      ? `Catalog up to date (${challenges.length} challenges, ${packs.length} packs)`
      : `Wrote catalog: ${challenges.length} challenges in ${packs.length} packs${stale ? "" : " (no changes)"}`))
    .catch((error) => { console.error(error.message); process.exit(1); });
}
